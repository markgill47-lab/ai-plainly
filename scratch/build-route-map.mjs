// Generates src/data/routeMap.js from us-atlas states-10m.json.
// Run: node scratch/build-route-map.mjs
import fs from 'node:fs'
import * as topojson from 'topojson-client'
import { geoConicConformal, geoPath } from 'd3-geo'

const topo = JSON.parse(fs.readFileSync('scratch/states-10m.json', 'utf8'))
const states = topojson.feature(topo, topo.objects.states)

// FIPS codes. Corridor states drawn solid, neighbors faded for context.
const CORRIDOR = { 27: 'MN', 19: 'IA', 29: 'MO', 5: 'AR', 47: 'TN', 28: 'MS', 17: 'IL' }
const CONTEXT = { 38: 'ND', 46: 'SD', 31: 'NE', 20: 'KS', 40: 'OK', 55: 'WI', 18: 'IN', 21: 'KY', 1: 'AL', 22: 'LA', 48: 'TX', 26: 'MI', 39: 'OH', 13: 'GA', 12: 'FL', 37: 'NC', 51: 'VA', 54: 'WV' }
const keep = states.features.filter(f => CORRIDOR[+f.id] || CONTEXT[+f.id])

const W = 640, H = 760
const proj = geoConicConformal().parallels([33, 45]).rotate([91, 0])
const corridorFC = { type: 'FeatureCollection', features: keep.filter(f => CORRIDOR[+f.id]) }
proj.fitExtent([[24, 24], [W - 24, H - 24]], corridorFC)
const path = geoPath(proj)

const fmt = (d) => d.replace(/(\d+\.\d{1})\d+/g, '$1')

const out = keep.map(f => ({
  id: CORRIDOR[+f.id] || CONTEXT[+f.id],
  corridor: !!CORRIDOR[+f.id],
  d: fmt(path(f)),
}))

// Waypoints, roughly following I-35 / US-61 / I-55 / US-49 / US-98.
const WAYPOINTS = [
  ['St. Cloud, MN', -94.163, 45.560, true],
  ['Minneapolis', -93.265, 44.978, false],
  ['Albert Lea', -93.368, 43.648, false],
  ['Des Moines, IA', -93.625, 41.587, true],
  ['Ottumwa', -92.411, 41.020, false],
  ['Hannibal', -91.358, 39.708, false],
  ['St. Louis, MO', -90.199, 38.627, true],
  ['Cape Girardeau', -89.518, 37.306, false],
  ['Blytheville', -89.919, 35.927, false],
  ['Memphis, TN', -90.049, 35.150, true],
  ['Grenada', -89.808, 33.769, false],
  ['Jackson, MS', -90.185, 32.299, true],
  ['Hattiesburg', -89.290, 31.327, false],
  ['Lucedale, MS', -88.590, 30.925, true],
]
const pts = WAYPOINTS.map(([name, lon, lat, major]) => {
  const [x, y] = proj([lon, lat])
  return { name, major, x: +x.toFixed(1), y: +y.toFixed(1) }
})

// Smooth open Catmull-Rom through the points, converted to cubic beziers.
function catmull(p) {
  let d = `M ${p[0].x} ${p[0].y}`
  for (let i = 0; i < p.length - 1; i++) {
    const p0 = p[i - 1] || p[i], p1 = p[i], p2 = p[i + 1], p3 = p[i + 2] || p2
    const c1x = p1.x + (p2.x - p0.x) / 6, c1y = p1.y + (p2.y - p0.y) / 6
    const c2x = p2.x - (p3.x - p1.x) / 6, c2y = p2.y - (p3.y - p1.y) / 6
    d += ` C ${c1x.toFixed(1)} ${c1y.toFixed(1)}, ${c2x.toFixed(1)} ${c2y.toFixed(1)}, ${p2.x} ${p2.y}`
  }
  return d
}

const js = `/* Generated by scratch/build-route-map.mjs from us-atlas states-10m (conic conformal). Do not edit by hand. */
export const VIEW = { w: ${W}, h: ${H} }
export const STATES = ${JSON.stringify(out)}
export const STOPS = ${JSON.stringify(pts)}
export const ROUTE = ${JSON.stringify(catmull(pts))}
`
fs.mkdirSync('src/data', { recursive: true })
fs.writeFileSync('src/data/routeMap.js', js)
console.log('wrote src/data/routeMap.js', (js.length / 1024).toFixed(0), 'KB, states:', out.length)
